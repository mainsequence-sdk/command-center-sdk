import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";

const applicationRoot = process.cwd();
const navigationPath = resolve(applicationRoot, "documentation/navigation.json");
const summaryPath = resolve(applicationRoot, "docs/SUMMARY.md");
const sidebarsPath = resolve(applicationRoot, "documentation/sidebars.mjs");
const check = process.argv.slice(2).includes("--check");

if (!existsSync(navigationPath)) {
  throw new Error("Missing documentation/navigation.json.");
}

const navigation = JSON.parse(readFileSync(navigationPath, "utf8"));
const normalized = normalizeNavigation(navigation);
const summary = renderSummary(normalized.sections);
const sidebars = renderSidebars(normalized);
const stale = [
  [summaryPath, summary],
  [sidebarsPath, sidebars],
].filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);

if (check && stale.length) {
  process.stderr.write(
    `${stale.map(([path]) => `- Generated documentation navigation is stale: ${path}`).join("\n")}\n`,
  );
  process.exit(1);
}

if (!check) {
  for (const [path, content] of stale) writeFileSync(path, content, "utf8");
}

process.stdout.write(
  check
    ? `Documentation navigation is synchronized for ${normalized.docIds.size} page(s).\n`
    : `Synchronized documentation navigation for ${normalized.docIds.size} page(s).\n`,
);

function normalizeNavigation(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("documentation/navigation.json must contain an object.");
  }
  if (value.schemaVersion !== 1) {
    throw new Error("documentation/navigation.json schemaVersion must be 1.");
  }
  if (!/^[a-z][A-Za-z0-9]*$/u.test(value.sidebarId || "")) {
    throw new Error("documentation/navigation.json sidebarId must be a stable identifier.");
  }
  if (!Array.isArray(value.sections) || value.sections.length !== 2) {
    throw new Error("documentation/navigation.json must contain the surfaces and technical sections.");
  }
  const docIds = new Set();
  const sections = value.sections.map((item, index) => normalizeItem(item, `sections[${index}]`, docIds));
  const roots = sections.map(({ doc }) => doc);
  if (roots[0] !== "surfaces/index" || roots[1] !== "technical/index") {
    throw new Error("Documentation sections must begin with surfaces/index and technical/index in that order.");
  }
  return { schemaVersion: 1, sidebarId: value.sidebarId, sections, docIds };
}

function normalizeItem(value, path, docIds) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${path} must be an object.`);
  }
  const label = typeof value.label === "string" ? value.label.trim() : "";
  const doc = typeof value.doc === "string" ? value.doc.trim() : "";
  if (!label || /[\r\n]/u.test(label)) throw new Error(`${path}.label must be one non-empty line.`);
  if (!/^(?:surfaces|technical)\/[a-z0-9][a-z0-9_/-]*$/u.test(doc) || doc.includes("..")) {
    throw new Error(`${path}.doc must be a safe surfaces/ or technical/ document ID.`);
  }
  if (docIds.has(doc)) throw new Error(`Duplicate documentation ID: ${doc}`);
  docIds.add(doc);
  const items = value.items ?? [];
  if (!Array.isArray(items)) throw new Error(`${path}.items must be an array.`);
  return {
    label,
    doc,
    items: items.map((item, index) => normalizeItem(item, `${path}.items[${index}]`, docIds)),
  };
}

function renderSummary(sections) {
  const lines = [
    "# Documentation",
    "",
    "This map and the Docusaurus sidebar are generated from `documentation/navigation.json`.",
    "",
  ];
  for (const section of sections) renderSummaryItem(section, 0, lines);
  return `${lines.join("\n")}\n`;
}

function renderSummaryItem(item, depth, lines) {
  const target = `${item.doc}.md`.replace(/\/index\.md$/u, "/index.md");
  lines.push(`${"  ".repeat(depth)}- [${item.label}](${target})`);
  for (const child of item.items) renderSummaryItem(child, depth + 1, lines);
}

function renderSidebars(navigation) {
  const sidebar = Object.fromEntries([
    [navigation.sidebarId, navigation.sections.map(renderSidebarItem)],
  ]);
  return [
    "// Generated by scripts/sync-docs-navigation.mjs. Do not edit directly.",
    `const sidebars = ${JSON.stringify(sidebar, null, 2)};`,
    "",
    "export default sidebars;",
    "",
  ].join("\n");
}

function renderSidebarItem(item) {
  return {
    type: "category",
    label: item.label,
    link: { type: "doc", id: item.doc },
    items: item.items.map(renderSidebarItem),
  };
}
